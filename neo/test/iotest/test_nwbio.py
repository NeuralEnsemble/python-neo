    def test_description_and_comments(self):
        nwbfile = _make_nwbfile()
        notes = {"protocol": "step", "amplitude": 5}
        nwbfile.add_acquisition(
            pynwb.TimeSeries(
                name="ts",
                data=np.arange(10.0),
                unit="volts",
                rate=10.0,
                description="membrane potential",
                comments="recorded on rig 2",
            )
        )
        nwbfile.add_acquisition(
            pynwb.TimeSeries(
                name="ts_notes", data=np.arange(10.0), unit="volts", rate=10.0, description=json.dumps(notes)
            )
        )
        nwbfile.add_acquisition(
            pynwb.TimeSeries(name="ts_number", data=np.arange(10.0), unit="volts", rate=10.0, description="42")
        )
        nwbfile.add_acquisition(
            pynwb.misc.AnnotationSeries(
                name="events", data=["a", "b"], timestamps=[0.1, 0.2], description=json.dumps(notes)
            )
        )
        path = self._write(nwbfile)

        def check(segment):
            signals = {sig.name: sig for sig in segment.analogsignals}
            self.assertEqual(signals["ts"].description, "membrane potential")
            self.assertEqual(signals["ts"].annotations["nwb:comments"], "recorded on rig 2")
            self.assertIsNone(signals["ts_notes"].description)
            self.assertEqual(signals["ts_notes"].annotations["notes"], notes)
            self.assertNotIn("nwb:comments", signals["ts_notes"].annotations)
            # a description that happens to be valid JSON, but not a JSON object, is kept as a string
            self.assertEqual(signals["ts_number"].description, "42")
            event = segment.events[0]
            self.assertIsNone(event.description)
            self.assertEqual(event.annotations["notes"], notes)
            self.assertNotIn("protocol", event.annotations)

        block = self._read(path)[0]
        check(block.segments[0])

        out_path = self.tmpdir / "rewritten.nwb"
        NWBIO(out_path, mode="w").write_all_blocks([block])
        check(self._read(out_path)[0].segments[0])

    def test_fields_not_accepted_by_class(self):
        # IZeroClampSeries has fixed values for bias_current etc., which can't be passed to the constructor
        nwbfile = _make_nwbfile()
        device = nwbfile.create_device(name="amplifier")
        electrode = nwbfile.create_icephys_electrode(name="elec0", description="patch pipette", device=device)
        nwbfile.add_acquisition(
            pynwb.icephys.IZeroClampSeries(
                name="izero", data=np.arange(10.0), electrode=electrode, rate=10.0, gain=1.0, sweep_number=0
            )
        )
        path = self._write(nwbfile)
        block = self._read(path)[0]
        self.assertIn("nwb:bias_current", block.segments[0].analogsignals[0].annotations)

        out_path = self.tmpdir / "rewritten.nwb"
        with self.assertLogs("neo.io.nwbio.NWBIO", level="WARNING"):
            NWBIO(out_path, mode="w").write_all_blocks([block])
        with pynwb.NWBHDF5IO(out_path, mode="r") as io:
            self.assertIsInstance(io.read().acquisition["izero"], pynwb.icephys.IZeroClampSeries)

