def _make_nwbfile():
    """Create a minimal NWBFile, as it might be created by software other than Neo."""
    return pynwb.NWBFile(
        session_description="test file",
        identifier="test-file",
        session_start_time=datetime(2020, 1, 1, tzinfo=timezone.utc),
    )


def _add_electrodes(nwbfile, n_electrodes):
    """Add electrodes to an NWBFile, and return a region covering all of them."""
    device = nwbfile.create_device(name="probe")
    group = nwbfile.create_electrode_group(name="shank0", description="shank", location="CA1", device=device)
    for i in range(n_electrodes):
        nwbfile.add_electrode(group=group, location="CA1")
    return nwbfile.create_electrode_table_region(list(range(n_electrodes)), "all electrodes")


@unittest.skipUnless(HAVE_PYNWB, "requires pynwb")
class TestNWBIOForeignFiles(unittest.TestCase):
    """Tests reading (and re-writing) NWB files that were not created by Neo."""

    def setUp(self):
        self._tmpdir = tempfile.TemporaryDirectory()
        self.tmpdir = Path(self._tmpdir.name)

    def tearDown(self):
        self._tmpdir.cleanup()

    def _write(self, nwbfile, name="foreign.nwb"):
        path = self.tmpdir / name
        with pynwb.NWBHDF5IO(path, mode="w") as io:
            io.write(nwbfile)
        return path

    def _read(self, path, lazy=False):
        blocks = NWBIO(path, mode="r").read_all_blocks(lazy=lazy)
        if lazy:
            for block in blocks:
                for segment in block.segments:
                    for proxy in segment.data_children:
                        self.assertIs(proxy.segment, segment)
        return blocks

    def test_read_lazy(self):
        nwbfile = _make_nwbfile()
        nwbfile.add_acquisition(
            pynwb.TimeSeries(name="ts", data=np.arange(10.0), unit="volts", rate=1000.0, starting_time=0.0)
        )
        path = self._write(nwbfile)
        segment = self._read(path, lazy=True)[0].segments[0]
        self.assertEqual(len(segment.analogsignals), 1)
        signal = segment.analogsignals[0].load()
        assert_array_equal(signal.magnitude.ravel(), np.arange(10.0))

    def test_fields_that_cannot_be_annotations(self):
        # The `electrodes` field of an ElectricalSeries is a link to rows of the electrodes table,
        # and string arrays are read as StrDataset; neither can be stored directly as an annotation
        nwbfile = _make_nwbfile()
        region = _add_electrodes(nwbfile, 4)
        nwbfile.keywords = ["hippocampus", "LFP"]
        nwbfile.add_acquisition(
            pynwb.ecephys.ElectricalSeries(name="es", data=np.ones((20, 4)), electrodes=region, rate=1000.0)
        )
        path = self._write(nwbfile)
        for lazy in (False, True):
            block = self._read(path, lazy=lazy)[0]
            assert_array_equal(block.annotations["keywords"], ["hippocampus", "LFP"])
            signal = block.segments[0].analogsignals[0]
            if lazy:
                signal = signal.load()
            self.assertEqual(signal.shape, (20, 4))
            self.assertNotIn("nwb:electrodes", signal.annotations)

        # writing back: we can't yet write the electrode information,
        # so the signal should be written as a generic TimeSeries
        out_path = self.tmpdir / "rewritten.nwb"
        with self.assertLogs("neo.io.nwbio.NWBIO", level="WARNING") as cm:
            NWBIO(out_path, mode="w").write_all_blocks([block])
        self.assertIn("ElectricalSeries", cm.output[0])
        with pynwb.NWBHDF5IO(out_path, mode="r") as io:
            rewritten = io.read()
            self.assertEqual(list(rewritten.keywords), ["hippocampus", "LFP"])
            self.assertEqual(type(rewritten.acquisition["es"]), pynwb.TimeSeries)

    def test_scaling(self):
        nwbfile = _make_nwbfile()
        raw = np.arange(40, dtype=np.int16).reshape(10, 4)
        # conversion factor that is not a power of ten, as used by e.g. Intan
        nwbfile.add_acquisition(
            pynwb.TimeSeries(
                name="not_power_of_ten", data=raw, unit="volts", rate=1000.0, conversion=0.195e-6, offset=-1e-3
            )
        )
        # conversion factor that can be expressed through the units
        nwbfile.add_acquisition(
            pynwb.TimeSeries(name="power_of_ten", data=raw, unit="volts", rate=1000.0, conversion=1e-3, offset=0.5)
        )
        region = _add_electrodes(nwbfile, 4)
        nwbfile.add_acquisition(
            pynwb.ecephys.ElectricalSeries(
                name="channel_conversion",
                data=raw,
                electrodes=region,
                rate=1000.0,
                conversion=1e-6,
                channel_conversion=[1.0, 2.0, 3.0, 4.0],
            )
        )
        path = self._write(nwbfile)
        with pynwb.NWBHDF5IO(path, mode="r") as io:
            nwbfile_in = io.read()
            expected = {name: ts.get_data_in_units() for name, ts in nwbfile_in.acquisition.items()}
        for lazy in (False, True):
            segment = self._read(path, lazy=lazy)[0].segments[0]
            for signal in segment.analogsignals:
                if lazy:
                    signal = signal.load()
                assert_allclose(signal.rescale("V").magnitude, expected[signal.name])
                for key in ("nwb:conversion", "nwb:offset", "nwb:channel_conversion"):
                    self.assertNotIn(key, signal.annotations)

        # the scaling should not be applied a second time when writing
        block = self._read(path)[0]
        out_path = self.tmpdir / "rewritten.nwb"
        NWBIO(out_path, mode="w").write_all_blocks([block])
        segment = self._read(out_path)[0].segments[0]
        for signal in segment.analogsignals:
            assert_allclose(signal.rescale("V").magnitude, expected[signal.name])

    def test_skip_unsupported_objects(self):
        # containers such as Position, and image data, are not yet supported,
        # but should not prevent the rest of the file being read
        nwbfile = _make_nwbfile()
        position = pynwb.behavior.Position(name="Position")
        position.create_spatial_series(
            name="pos", data=np.ones((10, 2)), reference_frame="origin", rate=10.0, starting_time=0.0
        )
        nwbfile.add_acquisition(position)
        nwbfile.add_acquisition(
            pynwb.image.ImageSeries(name="images", data=np.zeros((5, 4, 4)), unit="n.a.", rate=10.0)
        )
        nwbfile.add_acquisition(pynwb.TimeSeries(name="ts", data=np.arange(10.0), unit="volts", rate=10.0))
        path = self._write(nwbfile)
        for lazy in (False, True):
            segment = self._read(path, lazy=lazy)[0].segments[0]
            self.assertEqual([sig.name for sig in segment.analogsignals], ["ts"])

    def test_units_without_obs_intervals(self):
        nwbfile = _make_nwbfile()
        nwbfile.add_unit(spike_times=[0.5, 1.5, 2.5])
        nwbfile.add_unit(spike_times=[-0.5, 3.5])
        path = self._write(nwbfile)
        for lazy in (False, True):
            spiketrains = self._read(path, lazy=lazy)[0].segments[0].spiketrains
            if lazy:
                spiketrains = [st.load() for st in spiketrains]
            assert_array_equal(spiketrains[0].magnitude, [0.5, 1.5, 2.5])
            for st in spiketrains:
                self.assertEqual(st.t_start, -0.5 * pq.s)
                self.assertEqual(st.t_stop, 3.5 * pq.s)

    def test_units_with_multiple_obs_intervals(self):
        nwbfile = _make_nwbfile()
        nwbfile.add_unit(spike_times=[0.5, 1.5, 4.5], obs_intervals=[[0.0, 2.0], [4.0, 5.0]])
        # spikes outside the observation interval
        nwbfile.add_unit(spike_times=[0.5, 6.0], obs_intervals=[[0.0, 5.0]])
        path = self._write(nwbfile)
        spiketrains = self._read(path)[0].segments[0].spiketrains
        self.assertEqual(spiketrains[0].t_start, 0.0 * pq.s)
        self.assertEqual(spiketrains[0].t_stop, 5.0 * pq.s)
        assert_array_equal(spiketrains[0].annotations["nwb:obs_intervals"], [[0.0, 2.0], [4.0, 5.0]])
        assert_array_equal(spiketrains[1].magnitude, [0.5, 6.0])
        self.assertEqual(spiketrains[1].t_stop, 6.0 * pq.s)

        # the observation intervals should be preserved when writing
        out_path = self.tmpdir / "rewritten.nwb"
